// Command hostlist renders the supported inventory as Markdown, so
// README.md can state what the program supports without anyone maintaining
// that list by hand.
//
// A hand-written inventory is wrong within two commits, and wrong in the
// direction that matters: it under-reports, so a reader concludes their page
// is unsupported when it is not. This asks the registry instead. `make hosts`
// writes the output into README.md between two markers, and CI fails when the
// file and the code disagree.
//
// The prose table in docs/supported-links.md is deliberately NOT generated:
// it explains how a handful of interesting hosts resolve, which is a judgement
// about what deserves explaining. Only the inventory is mechanical.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/JohanLindvall/HeapLeach/internal/config"
	"github.com/JohanLindvall/HeapLeach/internal/extractor"
	"github.com/JohanLindvall/HeapLeach/internal/httpx"
)

// The markers the generated section is written between. Everything outside
// them is a person's prose and is left exactly as it was.
const (
	beginMarker = "<!-- BEGIN HOSTS -->"
	endMarker   = "<!-- END HOSTS -->"
)

func main() {
	countOnly := flag.Bool("count", false, "print the number of extractors and exit")
	write := flag.String("write", "", "rewrite the host section of this Markdown file in place")
	flag.Parse()

	// A registry built with the defaults: no environment additions, since
	// what is documented must be what the program ships with rather than
	// what one machine happens to be configured for.
	cfg := &config.Config{
		UserAgent: config.DefaultUserAgent,
		Language:  config.DefaultLanguage,
	}
	client := httpx.New(cfg.UserAgent, cfg.AcceptLanguage(), 0, 0)
	catalogue := extractor.NewRegistry(cfg, client).Catalogue()

	switch {
	case *countOnly:
		fmt.Println(len(catalogue))
	case *write != "":
		if err := rewrite(*write, render(catalogue)); err != nil {
			fmt.Fprintln(os.Stderr, "error:", err)
			os.Exit(1)
		}
		fmt.Printf(">> %s: %d extractors\n", *write, len(catalogue))
	default:
		if _, err := os.Stdout.WriteString(render(catalogue)); err != nil {
			fmt.Fprintln(os.Stderr, "error:", err)
			os.Exit(1)
		}
	}
}

// rewrite replaces the marked section of a Markdown file, leaving every other
// byte alone. Done here rather than in the Makefile so the whole generator is
// one program in one language, with no shell quoting between the two halves.
func rewrite(path, body string) error {
	doc, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	text := string(doc)

	start := strings.Index(text, beginMarker)
	end := strings.Index(text, endMarker)
	if start < 0 || end < start {
		return fmt.Errorf("%s has no %s / %s markers to write between", path, beginMarker, endMarker)
	}
	updated := text[:start] + beginMarker + "\n" + strings.TrimSpace(body) + "\n" + text[end:]
	if updated == text {
		return nil // already current; leave the mtime alone
	}
	return os.WriteFile(path, []byte(updated), 0o644)
}

// render writes the inventory as one Markdown table: every extractor and its
// own account of the pages it recognises. No row names a domain, because no
// extractor claims one: each is chosen by what a page serves.
func render(catalogue []extractor.HostInfo) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- Generated by `make hosts`. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "%d extractors, each chosen by what a page serves rather than by "+
		"its domain, so a site that moves, or an install nobody listed, is still "+
		"recognised.\n\n", len(catalogue))
	b.WriteString("| Extractor | Recognises |\n|---|---|\n")
	for _, host := range catalogue {
		fmt.Fprintf(&b, "| `%s` | %s |\n", host.Name, host.Recognises)
	}
	return b.String()
}
