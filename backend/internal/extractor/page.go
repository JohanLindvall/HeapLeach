// Page is what a URL answered when the registry asked it what it is.
//
// The registry fetches every submitted http(s) URL once, before choosing an
// extractor, and each extractor's Recognise reads this answer rather than the
// URL's host. A page that could not be read at all is still a Page — Err says
// why — so that an extractor whose URL form alone is conclusive can claim it,
// and the error it then meets is its own rather than the probe's.
//
// A Page's response is shared: the page cache keeps one for callers of its
// URL and route — a successful one for any route sending the same request
// (Page.servesAnyRoute). Each acquisition gets its own view and memo, shared
// only by that acquisition's recognisers and chosen extractor. Additional
// network answers cannot inherit the source document's cache lifetime.
// Everything it holds — its URLs, header, body, parsed document and memoised
// values — is borrowed and must not be changed. A reader that needs to edit
// a URL, a header or a subtree copies it first; probedDocument and fetchRoot
// already hand back a final URL the caller owns.
type Page struct {
	// URL is the URL as submitted; Final is where redirects ended.
	URL, Final *url.URL
	// Status is the HTTP status, zero when nothing answered.
	Status int
	// Header is the response's header, nil when nothing answered.
	Header http.Header
	// Body is the response, read when it is text of some kind: whole when
	// it is a document (markup, a script, JSON, XML, a playlist), bounded
	// by config.MaxResponseBytes; only its first config.ProbeSniffBytes
	// when it names no type or another text type (partial). Empty for
	// media, which the probe never reads.
	Body string
	// partial marks a Body read only as a prefix for sniffing, never to be
	// offered as the document or shared with another route.
	partial bool
	// originReferer records whether this acquisition already asked with
	// the origin as Referer, so an empty HTML page is not retried that way
	// again. Redirect-generated Referers do not count as that request.
	originReferer bool
	// referer is what the submitted request sent; finalReferer is what
	// reached Final, including a Referer generated by a redirect. Readers
	// with an explicit Referer policy must match the request for their URL.
	referer, finalReferer string
	// Challenged is set when a WAF challenge stood in for the page: there is
	// nothing of the site's own to read, only the URL.
	Challenged bool
	// Err is the fetch's failure, if it failed.
	Err error

	// via and route are who asked: the client, whose User-Agent, language
	// and cookie jar the answer was for, and the route it went out on. A
	// page built without them (a fixture) answers any reader. request is
	// the request as sent (httpx.RequestKey), by which another route may
	// share a successful answer. session snapshots the same identity after
	// the probe, so its own Set-Cookie does not make its reader fetch again.
	// A response that changes cookies is handed only to its original caller;
	// the cache neither keeps it nor shares it with waiting callers.
	via     *httpx.Client
	route   string
	agent   string
	request string
	session string
	// redirects records each request in a redirect chain and the cookies
	// left afterward. The submitted URL's key cannot see cookies scoped to
	// another hop's path or host. A chain setting cookies is not shared:
	// a hop may establish a cookie for a destination not yet visited.
	redirects       []pageRequest
	redirectCookies bool
	// noCache forbids reuse by another acquisition; the originating reader
	// can still consume its probe once. variesReferer and variesAgent record
	// representation dependencies readers must honor within that acquisition.
	// All include the responses along the redirect chain.
	noCache, variesReferer, variesAgent bool
	// reuseUntil bounds later acquisitions by the shortest freshness
	// lifetime in the response chain. Zero leaves only the local cache TTL.
	// It never prevents the originating reader from consuming its Page.
	reuseUntil time.Time

	// source owns the immutable response's parsed index. An acquisition view
	// borrows that index, but never source's memo: answers from other URLs
	// may have different freshness, cookies or representation policies.
	source *Page

	// parsed is filled once, on first use: the document and what every
	// recogniser asks of its head, read in one pass, since each unrecognised
	// page is offered to every recogniser in turn.
	parseOnce sync.Once
	parsed    pageIndex
	// indexed is set once parsed is filled, for a reader that takes the
	// tree only when recognition already built it (parsedRoot).
	indexed atomic.Bool

	memoMu sync.Mutex
	memo   map[string]*memoEntry
	// charged counts the bytes a memoised answer holds against the page
	// cache's bound. The cache sets it before handing the page out
	// (pageCache.get); nil for a page no cache keeps.
	charged func(int)
}

// acquisition retains the cached response and its lazy parsed document,
// with fresh memo state for one identification/extraction. Copy only immutable
// fields: the parse and memo locks must never be copied or reset while another
// acquisition uses them. Acquisition memos are not retained by the page cache.
func (p *Page) acquisition() *Page {
	return &Page{
		URL: p.URL, Final: p.Final, Status: p.Status, Header: p.Header, Body: p.Body,
		partial: p.partial, originReferer: p.originReferer,
		referer: p.referer, finalReferer: p.finalReferer,
		Challenged: p.Challenged, Err: p.Err,
		via: p.via, route: p.route, agent: p.agent,
		request: p.request, session: p.session,
		redirects: p.redirects, redirectCookies: p.redirectCookies,
		noCache: p.noCache, variesReferer: p.variesReferer, variesAgent: p.variesAgent, reuseUntil: p.reuseUntil,
		source: p,
	}
}

type pageRequest struct {
	url              *url.URL
	request, session string
}

// pageIndex is what one pass over the document collects.
type pageIndex struct {
	root *html.Node
	// meta maps each meta name and property to its first element's content.
	meta  map[string]string
	title string
	// scripts are the paths of the scripts the document loads.
	scripts []string
	names   []string
}

type memoEntry struct {
	// ready is closed once value is set.
	ready chan struct{}
	value any
	// dropped marks an answer memoAsked did not keep: one computed after
	// its asker's context had ended.
	dropped bool
}

// memoSlot returns the entry for key, and whether the caller created it
// and so computes its value.
func (p *Page) memoSlot(key string) (e *memoEntry, owner bool) {
	p.memoMu.Lock()
	defer p.memoMu.Unlock()
	if p.memo == nil {
		p.memo = map[string]*memoEntry{}
	}
	if e = p.memo[key]; e == nil {
		e = &memoEntry{ready: make(chan struct{})}
		p.memo[key] = e
		owner = true
	}
	return e, owner
}

// memo runs compute once per acquisition view and key, however many recognisers ask:
// a bounded probe of the page's origin that several extractors would make
// is made once, and its answer shared. Concurrent callers wait for the
// first. Keys are namespaced by what is asked ("json <endpoint>"), and a key
// is only ever asked for one type. Values on a cached source Page are charged
// through memoSize; acquisition views never retain their answers in that cache.
func memo[T any](p *Page, key string, compute func() T) T {
	e, owner := p.memoSlot(key)
	if owner {
		func() {
			defer close(e.ready)
			e.value = compute()
		}()
		p.charge(memoSize(e.value))
	}
	<-e.ready
	v, _ := e.value.(T)
	return v
}

// memoAsked is memo for a question compute puts to the network with ctx.
// An answer that comes back after ctx has ended is that caller's
// cancellation, not the page's answer: it is handed back to that caller
// alone and not kept, so callers sharing this acquisition's view go on as
// if nobody had asked, and a caller
// that was waiting on it asks again with its own context. Any other
// answer, failures and the probe's own timeouts included, is kept only in
// this acquisition's Page view. The next acquisition gets a new memo even
// when its source document can still be read from the page cache. A retry
// the user asked for (FreshRead) also reads that document afresh.
//
// A caller waiting for another's answer waits only as long as its own ctx
// lasts: the question runs under the first asker's context and admission,
// and a job cancelled meanwhile is not to stay blocked behind another
// job's queue of requests. It gets T's zero value, which its ended context
// makes moot, and nothing is kept for it.
//
// Answers are kept per route (memoKey): a page one route fetched may be
// read on another (Page.servesAnyRoute), but a question put to the network
// was put from one address, and a refusal or a limit met there says nothing
// of what another is answered.
func memoAsked[T any](ctx context.Context, p *Page, key string, compute func() T) T {
	key = memoKey(ctx, key)
	for {
		e, owner := p.memoSlot(key)
		if owner {
			var v T
			func() {
				defer close(e.ready)
				v = compute()
				e.value = v
				if ctx.Err() != nil {
					e.dropped = true
					p.memoMu.Lock()
					if p.memo[key] == e {
						delete(p.memo, key)
					}
					p.memoMu.Unlock()
				}
			}()
			if !e.dropped {
				p.charge(memoSize(v))
			}
			return v
		}
		select {
		case <-e.ready:
		case <-ctx.Done():
			var zero T
			return zero
		}
		if !e.dropped {
			v, _ := e.value.(T)
			return v
		}
	}
}

// memoSize is what a memoised value holds that the page cache counts: the
// bytes of a body, a document or a raw answer, and a whole page fetched
// beside this one. Anything else is small.
func memoSize(v any) int {
	switch v := v.(type) {
	case string:
		return len(v)
	case []byte:
		return len(v)
	case json.RawMessage:
		return len(v)
	case jsonAnswer:
		return len(v.raw)
	case *Page:
		if v != nil {
			return config.PageCacheEntryBytes + len(v.Body)
		}
	}
	return 0
}

// charge counts n more bytes p holds against the cache that lists it, if
// one still does.
func (p *Page) charge(n int) {
	if n > 0 && p.charged != nil {
		p.charged(n)
	}
}

// memoKey is a memoAsked key on ctx's route.
func memoKey(ctx context.Context, key string) string {
	return httpx.RouteID(ctx) + " " + key
}

// pageCache keeps recently probed pages so that one URL is fetched once:
// identification and the extractor share one acquisition, while several
// sources can reuse the response in distinct views with their own memos.
// Transfer-time refreshes ask again. Only a success read whole
// (Page.servesAnyRoute) is kept. It is
// keyed by route and request, and also indexed by the request alone
// (httpx.RequestKey: the URL, the language and the cookies it sends,
// whatever agent the route presents), and serves any route that would make
// that same request: only the address and agent differ. A probe that changes
// its request's cookies is not kept or shared: its answer may be a gate for
// the old session, while the next request sees an unlocked page.
//
// Nothing else is kept beyond the probe that got it. A probe that failed
// or met a challenge is not even shared with its waiters, who ask again.
// Any other answer — a refusal, an error page, a redirect left unfollowed
// — is handed to the readers already waiting for that probe on its route,
// and then dropped: what one egress address is refused says nothing of
// another, route recovery moves a read to another address precisely to ask
// again, and a refusal is often of the moment, so the next job or retry
// that asks is answered by the site rather than by a minute-old refusal.
//
// It is bounded by age and by bytes, oldest dropped first: each entry
// counts a fixed allowance (config.PageCacheEntryBytes, which bounds how
// many header-only answers it holds), its body and request identity. Memo
// values attached directly to the source Page are charged through Page.charge;
// the registry's acquisition views keep their network answers outside the cache.
type pageCache struct {
	mu      sync.Mutex
	entries map[string]*list.Element
	// shared indexes the entries any route may read, by request and
	// acquisition Referer policy.
	shared map[string]*list.Element
	order  list.List // of *pageCacheEntry, oldest first
	bytes  int
	// sweep drops expired entries when nothing else asks (sweepLocked).
	sweep   *time.Timer
	sweepAt time.Time
}

type pageCacheEntry struct {
	key string
	// request is set when shared indexes the entry.
	request string
	ready   chan struct{}
	page    *Page
	fetched time.Time
	// size is what the entry counts against config.PageCacheBytes: a
	// fixed allowance for the entry itself, its body and its page's
	// memoised answers (Page.charge).
	size int
}

// get returns the page for u through ctx's route, probing it at most once
// at a time and reusing a good answer for config.PageCacheTTL. A route with
// no answer of its own takes a success another route had for the same
// request. A fresh read (freshRead) takes no answer the cache already holds:
// it shares a probe still in flight on its route, which is no older than
// it, and otherwise probes again, its answer replacing the kept one. A probe
// in flight on another route is not waited for, since only its outcome says
// whether this route may share it.
func (c *pageCache) get(ctx context.Context, client *httpx.Client, u *url.URL) *Page {
	return c.getWithReferer(ctx, client, u, nil)
}

// getWithReferer acquires a known reader's representation. A nil policy is
// ordinary navigation, including its refusal retry; an explicit policy is
// a separate cache identity even when its Referer is empty.
func (c *pageCache) getWithReferer(ctx context.Context, client *httpx.Client, u *url.URL, referer *string) *Page {
	var key, request, representation string
	fresh := isFresh(ctx)
	for {
		request = httpx.RequestKey(ctx, client, u)
		representation = request
		if referer != nil {
			representation += "\n" + *referer
		}
		key = httpx.RouteID(ctx) + " " + representation
		c.mu.Lock()
		if c.entries == nil {
			c.entries = map[string]*list.Element{}
			c.shared = map[string]*list.Element{}
		}
		c.expireLocked()
		el := c.entries[key]
		if el == nil && !fresh && request != "" {
			if shared := c.shared[representation]; shared != nil {
				e := shared.Value.(*pageCacheEntry)
				p := e.page
				if p.matchesSession(ctx, client) && p.reusable() && time.Now().Before(e.expires()) {
					c.mu.Unlock()
					return p
				}
			}
		}
		if el == nil {
			break
		}
		e := el.Value.(*pageCacheEntry)
		if e.page != nil && (fresh || !e.page.matchesSession(ctx, client)) {
			c.removeLocked(el)
			break
		}
		c.mu.Unlock()
		select {
		case <-e.ready:
		case <-ctx.Done():
			return &Page{URL: u, Final: u, Err: ctx.Err()}
		}
		if e.page != nil && request == httpx.RequestKey(ctx, client, u) && e.page.matchesSession(ctx, client) &&
			e.page.reusable() && time.Now().Before(e.expires()) {
			return e.page
		}
		// A failed probe, or cookies changed while it ran, requires a new
		// question. Recompute its identity before looking in the cache.
	}
	e := &pageCacheEntry{key: key, ready: make(chan struct{})}
	c.entries[key] = c.order.PushBack(e)
	c.mu.Unlock()

	// The page keeps a URL of its own: the caller's may be changed once
	// the page is shared with others.
	p := probePageWithReferer(ctx, client, cloneURL(u), referer)
	c.mu.Lock()
	// The entry may have been dropped while its probe ran — evicted, or
	// replaced by a fresh read — and is then only its waiters' answer: a
	// page no longer listed is not counted against the bound.
	el := c.entries[key]
	listed := el != nil && el.Value == e
	unchanged := p.request == request && p.unchangedSession()
	if unchanged && p.reusable() && p.Err == nil && !p.Challenged {
		// Its waiters share any answer the site gave, refusals included.
		e.page, e.fetched = p, time.Now()
	}
	switch {
	case listed && unchanged && p.servesAnyRoute() && p.reusable():
		if request != "" {
			if old := c.shared[representation]; old != nil && old != el {
				old.Value.(*pageCacheEntry).request = ""
			}
			e.request = representation
			c.shared[representation] = el
		}
		e.size = config.PageCacheEntryBytes + len(p.Body) + len(p.referer) + len(p.finalReferer)
		for _, hop := range p.redirects {
			e.size += len(hop.url.String()) + len(hop.request) + len(hop.session)
		}
		c.bytes += e.size
		p.charged = c.charger(e)
		c.trimLocked()
		c.sweepLocked()
	case listed:
		c.removeLocked(el)
	}
	c.mu.Unlock()
	close(e.ready)
	return p
}

// expires bounds reuse by both the local TTL and the response's remaining
// freshness. The response deadline starts before the body is read.
func (e *pageCacheEntry) expires() time.Time {
	until := e.fetched.Add(config.PageCacheTTL)
	if e.page != nil && !e.page.reuseUntil.IsZero() && e.page.reuseUntil.Before(until) {
		until = e.page.reuseUntil
	}
	return until
}

// expireLocked drops expired entries. A probe still in flight has no
// page or fetch time and is left alone.
func (c *pageCache) expireLocked() {
	now := time.Now()
	for el := c.order.Front(); el != nil; {
		next := el.Next()
		if e := el.Value.(*pageCacheEntry); e.page != nil && !now.Before(e.expires()) {
			c.removeLocked(el)
		}
		el = next
	}
}

// sweepLocked arranges for expired entries to be dropped even when nothing
// asks the cache again: a burst of probes otherwise keeps its pages, their
// parsed documents and memoised answers several times their bodies' size,
// until the next probe of anything. One timer at a time, rearmed while
// entries remain.
func (c *pageCache) sweepLocked() {
	var next time.Time
	for el := c.order.Front(); el != nil; el = el.Next() {
		if e := el.Value.(*pageCacheEntry); e.page != nil {
			if until := e.expires(); next.IsZero() || until.Before(next) {
				next = until
			}
		}
	}
	if next.IsZero() || c.sweep != nil && !next.Before(c.sweepAt) {
		return
	}
	if c.sweep != nil {
		c.sweep.Stop()
	}
	var timer *time.Timer
	timer = time.AfterFunc(time.Until(next), func() {
		c.mu.Lock()
		defer c.mu.Unlock()
		if c.sweep != timer {
			return
		}
		c.sweep = nil
		c.expireLocked()
		if c.order.Len() > 0 {
			c.sweepLocked()
		}
	})
	c.sweep, c.sweepAt = timer, next
}

func (c *pageCache) removeLocked(el *list.Element) {
	e := c.order.Remove(el).(*pageCacheEntry)
	if c.entries[e.key] == el {
		delete(c.entries, e.key)
	}
	if e.request != "" && c.shared[e.request] == el {
		delete(c.shared, e.request)
	}
	c.bytes -= e.size
	e.size = 0
}

// trimLocked drops the oldest entries while the cache holds more than its
// bound, keeping the newest whatever its size.
func (c *pageCache) trimLocked() {
	for c.bytes > config.PageCacheBytes && c.order.Len() > 1 {
		c.removeLocked(c.order.Front())
	}
}

// charger is how a kept page counts what its memoised answers hold
// (Page.charge): against this cache's bound while the entry is listed, and
// not at all once it was dropped, when the page is only its readers'.
func (c *pageCache) charger(e *pageCacheEntry) func(int) {
	return func(n int) {
		c.mu.Lock()
		defer c.mu.Unlock()
		if el := c.entries[e.key]; el == nil || el.Value != e {
			return
		}
		e.size += n
		c.bytes += n
		c.trimLocked()
	}
}

// newProbePage snapshots who is about to ask for a page. Every real probe,
// including a recogniser's canonical request, must retain this identity so
// a later reader cannot consume another client's or session's response.
func newProbePage(ctx context.Context, client *httpx.Client, u *url.URL) *Page {
	return &Page{URL: u, Final: u, via: client, route: httpx.RouteID(ctx),
		agent: httpx.RequestAgent(ctx, client), request: httpx.RequestKey(ctx, client, u)}
}

// finishProbe snapshots the cookies left by the complete request chain.
// Its own reader can consume a response that set cookies without spending
// a single-use page again; a later session change still requires a new read.
func (p *Page) finishProbe(ctx context.Context) {
	p.session = httpx.RequestKey(ctx, p.via, p.URL)
	for i := range p.redirects {
		hop := &p.redirects[i]
		hop.session = httpx.RequestKey(ctx, p.via, hop.url)
	}
}

// probePage fetches a URL as a browser navigating to it would, reading the
// body only when it is text. A page that would not load is reported in the
// Page rather than as an error, since a recogniser may still know the URL's
// form.
//
// A named manifest is asked with the origin Referer its reader uses, so
// recognition and extraction can consume the same single-use response.
// Other probes navigate without a Referer. An answer of 401 or 403 is
// asked once more with the origin's root as the Referer, as the
// fallback's download and the manifest reader ask: a hotlink-protected
// file, or a manifest whose origin refuses strangers, is then read by what
// it serves its own pages rather than judged by the refusal. That second
// answer is the probe's.
//
// It spends little of the client's retry budget (probeDo): a recogniser
// that knows the URL's form claims a failed probe anyway, and the chosen
// extractor's own requests wait out what the probe did not.
func probePage(ctx context.Context, client *httpx.Client, u *url.URL) (p *Page) {
	return probePageWithReferer(ctx, client, u, nil)
}

// probePageWithReferer uses a reader's declared policy on the first GET.
// An explicit policy is not replaced with the generic origin refusal retry.
func probePageWithReferer(ctx context.Context, client *httpx.Client, u *url.URL, referer *string) (p *Page) {
	p = newProbePage(ctx, client, u)
	defer func() { p.finishProbe(ctx) }()
	if u.Scheme != "http" && u.Scheme != "https" {
		return p
	}
	if (!probeWorthy(u) || fileRoute(u)) && !hlsManifestShape(u) {
		// A link naming a file that some extractor's form claims: its
		// headers and redirects are asked for without fetching the file,
		// since a download link may be single-use or counted against a
		// quota, and a host that punishes parallel connections counts this
		// one too. Only an answer worth reading is fetched (headProbe).
		// A link naming a manifest is fetched at once: the manifest is
		// what its reader wants, and it takes the probe's copy
		// (fetchPlaylist) rather than spend a single-use link again.
		if head := headProbe(ctx, client, p); head != nil {
			return head
		}
	}
	var headers httpx.Header
	if referer != nil {
		headers = httpx.Referer(*referer)
	} else if hlsManifestShape(u) {
		headers = httpx.Referer(util.Origin(u) + "/")
	}
	if !probeGet(ctx, client, p, headers) {
		return p
	}
	if referer == nil && !p.originReferer && (p.Status == http.StatusUnauthorized || p.Status == http.StatusForbidden) {
		retry := &Page{URL: u, Final: u, via: p.via, route: p.route, agent: p.agent, request: p.request,
			redirects: p.redirects, redirectCookies: p.redirectCookies,
			noCache: p.noCache, variesReferer: p.variesReferer, variesAgent: p.variesAgent, reuseUntil: p.reuseUntil}
		if probeGet(ctx, client, retry, httpx.Referer(util.Origin(u)+"/")) || ctx.Err() != nil {
			return retry
		}
	}
	return p
}

// probeGet fills p with a GET of its URL, as a navigation with headers
// added. It reports whether anything answered: false leaves p's Err the
// failure.
func probeGet(ctx context.Context, client *httpx.Client, p *Page, headers httpx.Header) bool {
	req, err := client.NewRequest(ctx, http.MethodGet, p.URL.String(), nil)
	if err != nil {
		p.Err = err
		return false
	}
	httpx.Navigate.Apply(req)
	headers.Apply(req)
	p.referer = req.Header.Get(httpx.HeaderReferer)
	p.originReferer = p.referer == util.Origin(p.URL)+"/"
	started := time.Now()
	resp, err := probeDo(client, req)
	if err != nil {
		p.Err = err
		// Status errors display the submitted URL, but classification
		// still needs the destination that answered or failed to connect.
		if raw := httpx.ResponseURL(err); raw != "" {
			if final, parseErr := url.Parse(raw); parseErr == nil {
				p.Final = final
			}
		}
		_, p.Challenged = errors.AsType[*httpx.ChallengeError](err)
		return false
	}
	defer resp.Body.Close()
	p.Status, p.Header, p.Final = resp.StatusCode, resp.Header, resp.Request.URL
	p.finalReferer = resp.Request.Header.Get(httpx.HeaderReferer)
	p.recordRedirects(resp, started)
	kind := p.MediaType()
	switch {
	case probeReadsType(kind):
		// A body cut short — interrupted, or past the bound — is kept for
		// the recognisers to sniff, but the page is a failure: neither the
		// cache nor Document may offer a prefix as the document, which a
		// fetch of the same URL would refuse.
		body, err := httpx.ReadBody(resp.Body)
		if httpx.IsTooLarge(err) {
			err = fmt.Errorf("%s: %w", p.Final.Redacted(), err)
		}
		p.Err = err
		p.Body = string(body)
	case probeSniffsType(kind):
		// An answer that does not say it is a document is read only as far
		// as recognition looks: it is as likely to be a large file served
		// untyped. The prefix is never the document (Page.Document).
		body, _ := io.ReadAll(io.LimitReader(resp.Body, config.ProbeSniffBytes))
		p.Body, p.partial = string(body), true
	}
	return true
}

// probeDo is one request of the probe: a single attempt, and one more when
// that met a transient failure (probeTransient), after a short wait —
// config.PlatformProbeRetryWait for a rate limit, whatever it asks. A probe
// is not the place to wait out a limit or an outage: the chosen extractor's
// requests, and the transfer's, have budgets of their own.
func probeDo(client *httpx.Client, req *http.Request) (*http.Response, error) {
	resp, err := client.DoOnce(req)
	if err == nil || !probeTransient(req.Context(), err) {
		return resp, err
	}
	wait := httpx.RetryDelay(0)
	if httpx.HasStatus(err, http.StatusTooManyRequests) {
		wait = config.PlatformProbeRetryWait
	}
	if sleepErr := util.SleepCtx(req.Context(), wait); sleepErr != nil {
		return nil, sleepErr
	}
	return client.DoOnce(req)
}

// probeTransient reports whether a probe's failure is one a moment later
// may not repeat: no answer (a transport failure or a timeout), a rate
// limit, or a server error. A challenge, a refused route, an oversized
// body and cancellation are answers in their own right.
func probeTransient(ctx context.Context, err error) bool {
	if err == nil || ctx.Err() != nil || errors.Is(err, context.Canceled) || httpx.IsTooLarge(err) {
		return false
	}
	if _, challenged := errors.AsType[*httpx.ChallengeError](err); challenged {
		return false
	}
	if _, routed := errors.AsType[*httpx.RouteError](err); routed {
		return false
	}
	if status, ok := errors.AsType[*httpx.StatusError](err); ok {
		return status.Code == http.StatusTooManyRequests || status.Code == http.StatusRequestTimeout ||
			status.Code >= http.StatusInternalServerError
	}
	return true
}

// fileRoute is a link whose path names no file type and is a file all the
// same: a file API's download route (/api/file/<id>). It is probed as a
// link naming a file is, headers first, so that the probe neither starts
// the download nor reads a text file whole.
var fileRoute = pathShape(pixeldrainAPIFileForm)

// headProbe is p answered by a HEAD of its URL: the page itself when that
// says it is media, which a GET would only start downloading, and nil when
// the probe must GET after all — a text answer whose body recognition reads,
// or any answer but a success, since some servers refuse a method they do
// not serve or a URL signed for GET alone, and an error page's body is
// small and worth reading.
func headProbe(ctx context.Context, client *httpx.Client, p *Page) *Page {
	req, err := client.NewRequest(ctx, http.MethodHead, p.URL.String(), nil)
	if err != nil {
		return nil
	}
	httpx.Navigate.Apply(req)
	started := time.Now()
	resp, err := probeDo(client, req)
	if err != nil {
		if _, challenged := errors.AsType[*httpx.ChallengeError](err); challenged || ctx.Err() != nil {
			p.Err, p.Challenged = err, challenged
			return p
		}
		return nil
	}
	resp.Body.Close()
	p.recordRedirects(resp, started)
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil
	}
	kind, _, _ := mime.ParseMediaType(resp.Header.Get(httpx.HeaderContentType))
	if kind = strings.ToLower(kind); probeReadsType(kind) || probeSniffsType(kind) {
		return nil
	}
	p.Status, p.Header, p.Final = resp.StatusCode, resp.Header, resp.Request.URL
	p.finalReferer = resp.Request.Header.Get(httpx.HeaderReferer)
	return p
}

// recordRedirects keeps request identities and response reuse restrictions,
// not HTTP responses or their bodies. Request.Response links each hop to the
// one that caused it. Even a final cacheable response cannot override an
// earlier hop's no-store redirect or Referer-dependent destination.
func (p *Page) recordRedirects(resp *http.Response, started time.Time) {
	received := time.Now()
	redirected := resp.Request.Response != nil
	for resp != nil && resp.Request != nil {
		req := resp.Request
		until, reusable := pageFreshUntil(resp.Header, started, received)
		p.noCache = p.noCache || !reusable
		if !until.IsZero() && (p.reuseUntil.IsZero() || until.Before(p.reuseUntil)) {
			p.reuseUntil = until
		}
		for _, vary := range resp.Header.Values(httpx.HeaderVary) {
			for name := range strings.SplitSeq(vary, ",") {
				name = strings.TrimSpace(name)
				if name == "*" || strings.EqualFold(name, httpx.HeaderReferer) {
					p.variesReferer = true
				}
				if name == "*" || strings.EqualFold(name, httpx.HeaderUserAgent) {
					p.variesAgent = true
				}
				// Only these fields are modeled by RequestKey. Other
				// variants belong to this acquisition alone, even when
				// another caller uses the same route or browser.
				if name != "" && !strings.EqualFold(name, httpx.HeaderCookie) && !strings.EqualFold(name, httpx.HeaderAcceptLanguage) {
					p.noCache = true
				}
			}
		}
		if redirected {
			p.redirects = append(p.redirects, pageRequest{url: cloneURL(req.URL), request: httpx.SentRequestKey(req)})
			p.redirectCookies = p.redirectCookies || len(resp.Cookies()) != 0
		}
		resp = req.Response
	}
}

// pageFreshUntil is the response's freshness deadline, without the local
// cache TTL. max-age takes precedence over Expires; Age and Date account
// for time already spent in upstream caches. The whole probe's duration
// conservatively bounds each redirect hop's response delay, so fetching a
// slow destination or body never gives an earlier response extra life.
// Invalid or conflicting freshness metadata permits only the original
// acquisition to consume the answer. No stated lifetime leaves the local
// TTL in charge.
func pageFreshUntil(h http.Header, started, received time.Time) (time.Time, bool) {
	var lifetime time.Duration
	hasMaxAge := false
	for _, control := range h.Values(httpx.HeaderCacheControl) {
		for directive := range strings.SplitSeq(control, ",") {
			name, value, _ := strings.Cut(directive, "=")
			switch strings.ToLower(strings.TrimSpace(name)) {
			case httpx.CacheControlNoStore, httpx.CacheControlNoCache:
				return time.Time{}, false
			case httpx.CacheControlMaxAge:
				if hasMaxAge {
					return time.Time{}, false
				}
				hasMaxAge = true
				value = strings.TrimSpace(value)
				if len(value) >= 2 && value[0] == '"' && value[len(value)-1] == '"' {
					value = value[1 : len(value)-1]
				}
				var ok bool
				if lifetime, ok = cacheSeconds(value); !ok {
					return time.Time{}, false
				}
			}
		}
	}
	expires := h.Values(httpx.HeaderExpires)
	if !hasMaxAge && len(expires) == 0 {
		return time.Time{}, true
	}
	date := received
	if values := h.Values(httpx.HeaderDate); len(values) != 0 {
		var err error
		if len(values) != 1 {
			return time.Time{}, false
		}
		if date, err = http.ParseTime(values[0]); err != nil {
			return time.Time{}, false
		}
	}
	if !hasMaxAge {
		if len(expires) != 1 {
			return time.Time{}, false
		}
		end, err := http.ParseTime(expires[0])
		if err != nil {
			return time.Time{}, false
		}
		lifetime = end.Sub(date)
	}
	var age time.Duration
	if values := h.Values(httpx.HeaderAge); len(values) != 0 {
		var ok bool
		if len(values) != 1 {
			return time.Time{}, false
		}
		if age, ok = cacheSeconds(strings.TrimSpace(values[0])); !ok {
			return time.Time{}, false
		}
	}
	if lifetime <= age {
		return received, false
	}
	until := started.Add(lifetime - age)
	// A future Date cannot increase freshness beyond the response's
	// lifetime; an old Date can shorten it below what Age alone states.
	if date.After(received) {
		date = received
	}
	if dated := date.Add(lifetime); dated.Before(until) {
		until = dated
	}
	return until, received.Before(until)
}

// cacheSeconds reads HTTP delta-seconds without allowing signed, fractional
// or overflowing values to wrap into a new freshness lifetime. A valid
// duration larger than Go represents saturates; the local TTL still caps it.
func cacheSeconds(value string) (time.Duration, bool) {
	for _, c := range value {
		if c < '0' || c > '9' {
			return 0, false
		}
	}
	n, err := strconv.ParseUint(value, 10, 64)
	if err != nil {
		return 0, false
	}
	const maxDuration = time.Duration(1<<63 - 1)
	if n > uint64(maxDuration/time.Second) {
		return maxDuration, true
	}
	return time.Duration(n) * time.Second, true
}

// matchesSession checks every URL whose cookies contributed to this page,
// including intermediate redirects absent from both URL and Final.
func (p *Page) matchesSession(ctx context.Context, client *httpx.Client) bool {
	if p.session == "" || p.session != httpx.RequestKey(ctx, client, p.URL) {
		return false
	}
	for _, hop := range p.redirects {
		if hop.session != httpx.RequestKey(ctx, client, hop.url) {
			return false
		}
	}
	return true
}

// unchangedSession permits sharing only when all hops sent the cookies
// still in the jar. A cookie-setting redirect belongs to its caller alone,
// even when a later hop already sent the cookie an earlier hop established.
func (p *Page) unchangedSession() bool {
	if p.request != p.session || p.redirectCookies {
		return false
	}
	for _, hop := range p.redirects {
		if hop.request != hop.session {
			return false
		}
	}
	return true
}

// probeReadsType reports whether a response of this type is a document the
// probe reads whole, up to config.MaxResponseBytes: markup, JSON, XML, a
// script or a playlist. Media is never read, which is what keeps a probe of
// a direct link to a large file down to its headers.
func probeReadsType(kind string) bool {
	switch {
	case mediaPageIsHTMLType(kind), strings.HasSuffix(kind, "json"), strings.HasSuffix(kind, "xml"),
		strings.HasSuffix(kind, "javascript"), strings.Contains(kind, "mpegurl"):
		return true
	}
	return false
}

// probeSniffsType reports whether a response of this type is read only as
// far as config.ProbeSniffBytes: no type at all, or text that is no
// document of a kind the probe reads whole (plain text, CSV, a log), which
// may as well be a large file as a page.
func probeSniffsType(kind string) bool {
	return kind == "" || strings.HasPrefix(kind, "text/") && !probeReadsType(kind)
}

// pageKey carries the probed page to the chosen extractor, so one that reads
// the same document need not fetch it twice.
type pageKey struct{}

func withPage(ctx context.Context, p *Page) context.Context {
	return context.WithValue(ctx, pageKey{}, p)
}

// freshRead is ctx for a read that must ask the site again rather than take
// the page the registry probed: a retry of an answer that was received but
// wrong, and every read at transfer time, whose signed link or metadata the
// probe's would have made stale. Everything else ctx carries — cancellation,
// route, cookie jar, logger, challenge capture — stays as it was; only the
// probed page is withheld, so fetchDocument, fetchRoot and probedDocument
// fetch as if there had been none.
//
// Freshness is decided here, once, rather than by each reader: a reader
// takes the ctx it is handed and never one it captured earlier.
//
// The page cache honours it too (pageCache.get): a fresh read that goes
// back through the registry — a file refreshed at transfer time, a retry —
// is probed again rather than handed the page the cache kept from the
// listing, and the new answer replaces it.
func freshRead(ctx context.Context) context.Context {
	if !isFresh(ctx) {
		ctx = context.WithValue(ctx, freshKey{}, true)
	}
	if attachedPage(ctx) == nil {
		return ctx
	}
	return context.WithValue(ctx, pageKey{}, (*Page)(nil))
}

// FreshRead is freshRead for a read the user asked for again: a retry of a
// job whose source failed or must be listed anew. Registry.Extract then
// probes the source rather than take the document the cache kept. Every
// acquisition already starts with its own memo; a "no" kept about a whole install
// (verdictMemo) is asked again. Nested sources it lists are read afresh too.
func FreshRead(ctx context.Context) context.Context { return freshRead(ctx) }

// freshKey marks a context freshRead made.
type freshKey struct{}

// isFresh reports whether ctx is a fresh read's.
func isFresh(ctx context.Context) bool {
	fresh, _ := ctx.Value(freshKey{}).(bool)
	return fresh
}

// attachedPage is the page carried in ctx, whatever URL it answers.
func attachedPage(ctx context.Context) *Page {
	p, _ := ctx.Value(pageKey{}).(*Page)
	return p
}

// probed is the page the registry probed for u, carried in ctx, or nil when
// there is none for this URL. Either end of the redirect chain will do: an
// extractor that rebuilds the canonical address the submitted link
// redirected to is asking for the same page.
func probed(ctx context.Context, u *url.URL) *Page {
	p := attachedPage(ctx)
	if p == nil || u == nil {
		return nil
	}
	if p.via != nil {
		// Later cookie changes invalidate even a same-route probe. The
		// probe's own Set-Cookie is already included in its handoff state.
		if !p.matchesSession(ctx, p.via) {
			return nil
		}
		// A response restricted to its acquisition must keep that
		// acquisition's effective browser too. Reusing a route ID does
		// not make a changed WithRouteAgent override the same request.
		if p.noCache && p.agent != httpx.RequestAgent(ctx, p.via) {
			return nil
		}
		// Another route may read only a complete success that did not
		// change its session: its cookies were not updated by this probe.
		if p.route != httpx.RouteID(ctx) && !(p.servesAnyRoute() && p.unchangedSession()) {
			return nil
		}
	}
	if want := u.String(); p.URL.String() != want && p.Final.String() != want {
		return nil
	}
	return p
}

// servesAnyRoute reports whether the page is an answer any route sending
// the same request may read: a success, read whole. A refusal, an error
// page or a redirect left unfollowed may be the address's own, and a read
// moved to another route by recovery must ask again. A response forbidding
// caching belongs only to its originating acquisition.
func (p *Page) servesAnyRoute() bool {
	return p != nil && p.Err == nil && !p.Challenged && !p.partial && !p.noCache && p.Status >= 200 && p.Status < 300
}

// reusable checks freshness at acquisition, not while an extractor consumes
// an already-attached Page. A page acquired on another route just before
// expiry is still that extraction's answer and need not be fetched again.
func (p *Page) reusable() bool {
	return p != nil && !p.noCache && (p.reuseUntil.IsZero() || time.Now().Before(p.reuseUntil))
}

// Document is the page's body when it is a successful document of its own,
// the only kind an extractor may read instead of fetching. Both 200 and
// 203 carry the requested representation; 203 permits an intermediary's
// transformation. Other successes can describe an operation, omit content,
// or carry only a range or delta, so they do not establish a whole document.
func (p *Page) Document() (string, bool) {
	if p == nil || p.Err != nil || p.partial || p.Body == "" ||
		p.Status != http.StatusOK && p.Status != http.StatusNonAuthoritativeInfo {
		return "", false
	}
	return p.Body, true
}

// probedDocument returns the page the registry already fetched for u, when it
// is a successful document. ok is false whenever the extractor must fetch it
// itself: another URL, a failure, or a body the probe did not read. The final
// URL is a copy the caller may change, as it may one GetPage returned.
func probedDocument(ctx context.Context, u *url.URL) (doc string, final *url.URL, ok bool) {
	p := probed(ctx, u)
	if doc, ok = p.Document(); !ok {
		return "", nil, false
	}
	return doc, cloneURL(p.Final), true
}

// cloneURL is a copy of u its holder may change without changing u. The
// user information is immutable, so it may be shared.
func cloneURL(u *url.URL) *url.URL {
	if u == nil {
		return nil
	}
	c := *u
	return &c
}

// probedFor is the probed page for u when it is the response a GET of u
// with headers, through client on ctx's route, would get (Page.answers);
// nil when the reader must ask for its own.
func probedFor(ctx context.Context, client *httpx.Client, u *url.URL, headers httpx.Header) *Page {
	if p := probed(ctx, u); p.answers(client, u, headers) {
		return p
	}
	return nil
}

// answers reports whether p stands for a GET of its URL with headers
// through client: the one place a reader's request is held to the probe's.
// The probe navigated with no Referer, the origin's (for a named manifest
// or after a 401/403), or a known canonical player's declared policy,
// through the registry's client on a route probed checks. A client of another identity —
// another User-Agent, language or session (httpx.Client.SameIdentity) — is
// served its own representation, and so is a request carrying any header
// but a matching Referer: an Accept, a cookie, a credential or an agent of
// its own. A reader specifying a Referer, even an empty one, must receive
// that request's representation. With no Referer policy it accepts the
// probe's navigation, including its redirects and refusal retry. Other
// methods and request bodies never reach the probe: these readers GET.
func (p *Page) answers(client *httpx.Client, u *url.URL, headers httpx.Header) bool {
	if p == nil {
		return false
	}
	if p.via != nil && client != nil && !p.via.SameIdentity(client) {
		return false
	}
	for name, value := range headers {
		if !strings.EqualFold(name, httpx.HeaderReferer) {
			return false
		}
		if p.via != nil {
			referer := p.referer
			if u.String() != p.URL.String() {
				referer = p.finalReferer
			}
			if value != referer {
				return false
			}
		}
	}
	return true
}

// acquire is the one place a reader's page is obtained: the registry's
// probe when it is the response this request would get (probedFor) and a
// successful document of its own (Page.Document), otherwise a GetPage of
// u. A probe that failed, answered another status, or was read only in
// part is never offered; the reader fetches for itself. The document's
// final URL is the caller's own either way, and the probe's tree, when
// recognition built one, is borrowed rather than parsed again.
//
// fetchDocument, readDocument and fetchRoot are this with the result in the
// form each reader wants it. probe is the page reused, nil after a fetch.
func acquire(ctx context.Context, client *httpx.Client, u *url.URL, headers httpx.Header) (body string, final *url.URL, probe *Page, err error) {
	if p := probedFor(ctx, client, u, headers); p != nil {
		if body, ok := p.Document(); ok {
			return body, cloneURL(p.Final), p, nil
		}
	}
	body, final, err = client.GetPage(ctx, u.String(), headers, nil)
	return body, final, nil, err
}

// fetchDocument is GetPage for the submitted URL that reuses the registry's
// probe when it already holds the document, so a page an extractor reads
// whole is fetched once rather than once to recognise and again to read.
// Any other URL, a probe that did not get the page, or a request the probe
// does not answer (Page.answers) is fetched as usual.
func fetchDocument(ctx context.Context, client *httpx.Client, u *url.URL, headers httpx.Header) (string, *url.URL, error) {
	body, final, _, err := acquire(ctx, client, u, headers)
	if err != nil {
		return "", nil, err
	}
	return body, final, nil
}

// document is a page read whole, as a reader may want it: its body, where
// it was served from, and its tree, parsed on first use — the probe's own
// when recognition parsed the page, which is shared and only read.
type document struct {
	body  string
	final *url.URL
	probe *Page

	once    sync.Once
	root    *html.Node
	rootErr error
}

// parse is the document's tree, built once: the probe's when recognition
// already parsed it, otherwise the body parsed here, with the error of a
// body that will not parse. Taking the probe's tree never indexes a page
// that recognition did not, so a reader that wants only a tree costs no
// more than its own parse.
func (d *document) parse() (*html.Node, error) {
	d.once.Do(func() { d.root, d.rootErr = parseDocument(d.body, d.probe) })
	return d.root, d.rootErr
}

// parseDocument is body's tree: probe's when recognition already parsed it,
// otherwise body parsed now, with the error of one that will not parse.
func parseDocument(body string, probe *Page) (*html.Node, error) {
	if probe != nil {
		if root, _ := probe.parsedRoot(); root != nil {
			return root, nil
		}
	}
	return parseHTML(body)
}

// tree is the parsed document, or nil for a body that will not parse; a
// reader that needs it says so.
func (d *document) tree() *html.Node {
	root, _ := d.parse()
	return root
}

// readDocument is fetchDocument with the page's tree to hand: a reader that
// scans the body never parses it, and one that reads the tree parses it once
// or takes the probe's.
func readDocument(ctx context.Context, client *httpx.Client, u *url.URL, headers httpx.Header) (*document, error) {
	body, final, probe, err := acquire(ctx, client, u, headers)
	if err != nil {
		return nil, err
	}
	return &document{body: body, final: final, probe: probe}, nil
}

// fetchPage is fetchDocument for a link held as a string.
func fetchPage(ctx context.Context, client *httpx.Client, link string, headers httpx.Header) (string, error) {
	u, err := url.Parse(link)
	if err != nil {
		return "", err
	}
	doc, _, err := fetchDocument(ctx, client, u, headers)
	return doc, err
}

// fetchRoot is fetchDocument parsed: the probe's own tree when it is reused,
// so a document read to recognise it is not parsed a second time. That tree
// is the page's and is shared: a reader that removes or rewrites nodes parses
// its own copy instead. A document recognition did not parse — its
// recognisers only scanned the body, or the probe did not take it for HTML
// for want of a declared type — is still the one asked for, and is parsed
// here rather than fetched again. The final URL is the caller's own.
func fetchRoot(ctx context.Context, client *httpx.Client, u *url.URL, headers httpx.Header) (*html.Node, *url.URL, error) {
	body, final, probe, err := acquire(ctx, client, u, headers)
	if err != nil {
		return nil, nil, err
	}
	root, err := parseDocument(body, probe)
	return root, final, err
}

// fetchPageRoot is fetchRoot for a link held as a string.
func fetchPageRoot(ctx context.Context, client *httpx.Client, link string, headers httpx.Header) (*html.Node, error) {
	u, err := url.Parse(link)
	if err != nil {
		return nil, err
	}
	root, _, err := fetchRoot(ctx, client, u, headers)
	return root, err
}

// OK reports whether the page answered with content of its own.
func (p *Page) OK() bool { return p.Err == nil && p.Status >= 200 && p.Status < 300 }

// MediaType is the response's declared type, lower case and without
// parameters.
func (p *Page) MediaType() string {
	if p.Header == nil {
		return ""
	}
	kind, _, _ := mime.ParseMediaType(p.Header.Get(httpx.HeaderContentType))
	return strings.ToLower(kind)
}

// IsHTML reports whether the body is a document worth parsing.
func (p *Page) IsHTML() bool {
	kind := p.MediaType()
	return p.Body != "" && (mediaPageIsHTMLType(kind) || kind == "" && strings.Contains(p.Body[:min(len(p.Body), 1024)], "<"))
}

// index parses the document once and reads its head in the same pass.
func (p *Page) index() *pageIndex {
	if p.source != nil {
		return p.source.index()
	}
	p.parseOnce.Do(func() {
		if !p.IsHTML() {
			return
		}
		root, err := parseHTML(p.Body)
		if err != nil {
			return
		}
		x := &p.parsed
		x.root, x.meta = root, map[string]string{}
		walk(root, func(n *html.Node) {
			switch {
			case isElem(n, atom.Meta):
				content := strings.TrimSpace(attr(n, "content"))
				for _, key := range []string{attr(n, "property"), attr(n, "name")} {
					if _, seen := x.meta[key]; key != "" && !seen {
						x.meta[key] = content
					}
				}
			case isElem(n, atom.Title):
				if x.title == "" {
					x.title = strings.TrimSpace(textOf(n))
				}
			case isElem(n, atom.Script):
				if src, err := url.Parse(attr(n, "src")); err == nil && src.Path != "" {
					x.scripts = append(x.scripts, src.Path)
				}
			}
		})
		for _, key := range []string{"og:site_name", "application-name", "apple-mobile-web-app-title"} {
			if v := x.meta[key]; v != "" {
				x.names = append(x.names, v)
			}
		}
		if x.title != "" {
			parts := titleSeparators.Split(x.title, -1)
			x.names = append(x.names, parts[0])
			if len(parts) > 1 {
				x.names = append(x.names, parts[len(parts)-1])
			}
		}
	})
	p.indexed.Store(true)
	return &p.parsed
}

// parsedRoot is the page's tree when recognition has already parsed it,
// and false when nothing has yet. A reader that only wants a tree, not the
// index Page.HTML builds beside it, parses the body itself in that case:
// that costs less than the index, and a page whose recognisers only scan
// its body is never indexed for nothing.
func (p *Page) parsedRoot() (*html.Node, bool) {
	if p.source != nil {
		return p.source.parsedRoot()
	}
	if !p.indexed.Load() {
		return nil, false
	}
	return p.parsed.root, true
}

// HTML is the parsed document, or nil when the body is not one.
func (p *Page) HTML() *html.Node { return p.index().root }

// hasElement reports whether the document has an element the test accepts.
func (p *Page) hasElement(test func(n *html.Node) bool) bool {
	root := p.HTML()
	return root != nil && findFirst(root, test) != nil
}

// Has reports whether the body contains every one of the fragments.
func (p *Page) Has(fragments ...string) bool {
	if p.Body == "" {
		return false
	}
	for _, f := range fragments {
		if !strings.Contains(p.Body, f) {
			return false
		}
	}
	return true
}

// HasAny reports whether the body contains at least one of the fragments.
func (p *Page) HasAny(fragments ...string) bool {
	return slices.ContainsFunc(fragments, func(f string) bool { return p.Has(f) })
}

// Meta is a meta element's content by name or property.
func (p *Page) Meta(key string) string { return p.index().meta[key] }

// Generator is the generator meta tag, lower case: what software made the
// page, by its own account.
func (p *Page) Generator() string { return strings.ToLower(p.Meta("generator")) }

// Title is the document's title, trimmed.
func (p *Page) Title() string { return p.index().title }

// titleSeparators split a title into the page's own name and the site's.
var titleSeparators = regexp.MustCompile(`\s+[-|—–·:»]{1,2}\s+`)

// Names are what the page says the site is called: its og:site_name,
// application-name and web-app title, and the first and last parts of its
// title. A site's own name is the steadiest thing its pages carry — bundles
// are renamed with every deploy, while the name is on the root, on every
// content page and on its error pages alike.
func (p *Page) Names() []string { return p.index().names }

// namedBy reports whether one of the page's names for its site, trimmed,
// passes the test.
func (p *Page) namedBy(test func(name string) bool) bool {
	return slices.ContainsFunc(p.Names(), func(name string) bool { return test(strings.TrimSpace(name)) })
}

// Named reports whether the page calls its site any of the names, ignoring
// case and surrounding space.
func (p *Page) Named(names ...string) bool {
	return p.namedBy(func(have string) bool {
		return slices.ContainsFunc(names, func(want string) bool { return strings.EqualFold(have, want) })
	})
}

// namedPrefix reports whether one of the page's names for its site begins
// with the prefix, ignoring case: for a site whose name carries a varying
// tail, as "<Name> ex <old name>" does.
func (p *Page) namedPrefix(prefix string) bool {
	return p.namedBy(func(name string) bool {
		return len(name) >= len(prefix) && strings.EqualFold(name[:len(prefix)], prefix)
	})
}

// Script reports whether the document loads a script whose path contains
// the fragment. Only the path is compared, never the host it is served from.
func (p *Page) Script(fragment string) bool {
	return slices.ContainsFunc(p.index().scripts, func(path string) bool { return strings.Contains(path, fragment) })
}

// playerMetaKeys are the meta tags a video page names its embeddable player
// in. A site's own player is the steadiest structural fact a watch page
// carries: it is what every other site embeds, so it survives redesigns of
// the page around it.
var playerMetaKeys = []string{"twitter:player", "og:video:url", "og:video:secure_url", "og:video"}

// playerMeta reports whether the page names a player whose URL has the
// form; only its path, query and fragment are read.
func (p *Page) playerMeta(form func(*url.URL) bool) bool {
	return slices.ContainsFunc(playerMetaKeys, func(key string) bool {
		u, err := url.Parse(p.Meta(key))
		return err == nil && u.Path != "" && form(u)
	})
}

// frames reports whether the document frames a page whose URL, resolved
// against the page's own, has the form. A landing page that wraps a player
// is recognised by the player it frames.
func (p *Page) frames(form func(*url.URL) bool) bool {
	return p.hasElement(func(n *html.Node) bool {
		if !isElem(n, atom.Iframe) {
			return false
		}
		src, err := p.Final.Parse(attr(n, "src"))
		return err == nil && form(src)
	})
}

// Segments are the final URL's path segments.
func (p *Page) Segments() []string { return util.PathSegments(p.Final) }

// pathShape builds a URL-form test from patterns matched against the path
// alone. A form is the half of recognition that needs no fetch, and so the
// half the link scanner can use, which is why it never looks at the host.
func pathShape(patterns ...string) func(*url.URL) bool {
	res := make([]*regexp.Regexp, len(patterns))
	for i, p := range patterns {
		res[i] = regexp.MustCompile(p)
	}
	return func(u *url.URL) bool {
		for _, re := range res {
			if re.MatchString(u.EscapedPath()) {
				return true
			}
		}
		return false
	}
}

// pathQueryShape is pathShape for a form that names its query too: the
// pattern is matched against the escaped path, "?" and the raw query.
func pathQueryShape(pattern string) func(*url.URL) bool {
	re := regexp.MustCompile(pattern)
	return func(u *url.URL) bool { return re.MatchString(u.EscapedPath() + "?" + u.RawQuery) }
}

// verdictMemo remembers per host whether it answered a yes-or-no question
// about the whole install — "does this origin serve the platform's API" —
// so a run of links to one site asks it once rather than once a link. A
// yes is kept for the extractor's lifetime, as hostMemo keeps an answer; a
// no for config.OriginVerdictTTL, since a site that is not the platform is
// asked again by every link of the right form on it, and a no that was a
// bad moment should not outlive it for long. Only a no the site gave is
// kept: one that stands for no answer — a busy or unreachable site — is
// the next link's to ask again. An answer computed after the asker's
// context ended is not kept. The zero value is ready to use.
type verdictMemo struct {
	mu sync.Mutex
	m  map[string]verdict
}

type verdict struct {
	yes bool
	at  time.Time
}

// ask answers for host from memory, or with compute, remembering a yes and
// a definite no. compute reports whether its answer is definite: a no is
// only when the site itself answered the question (a success that is not
// the platform's answer, or a refusal of the endpoint), never when it was
// not asked or not answered — a timeout, a rate limit, a server error, a
// challenge, a check skipped. A fresh read (FreshRead, a retry the user
// asked for) takes no kept no and asks again.
func (v *verdictMemo) ask(ctx context.Context, host string, compute func() (yes, definite bool)) bool {
	host = strings.ToLower(host)
	v.mu.Lock()
	got, ok := v.m[host]
	v.mu.Unlock()
	if ok && (got.yes || (!isFresh(ctx) && time.Since(got.at) < config.OriginVerdictTTL)) {
		return got.yes
	}
	yes, definite := compute()
	if ctx.Err() != nil || !(yes || definite) {
		return yes
	}
	v.mu.Lock()
	if v.m == nil {
		v.m = make(map[string]verdict)
	}
	v.m[host] = verdict{yes: yes, at: time.Now()}
	v.mu.Unlock()
	return yes
}

// hostMemo remembers one answer per host for the extractor's lifetime: what
// a platform install established about itself — the software it runs, where
// it keeps its API — which no install changes between one paste and the next.
// The zero value is ready to use.
type hostMemo[T any] struct {
	mu sync.Mutex
	m  map[string]T
}

// lookup answers for host from memory, or with compute, remembering what it
// answered. A failure is not remembered: the next paste asks again.
func (h *hostMemo[T]) lookup(host string, compute func() (T, error)) (T, error) {
	host = strings.ToLower(host)
	h.mu.Lock()
	v, ok := h.m[host]
	h.mu.Unlock()
	if ok {
		return v, nil
	}
	v, err := compute()
	if err != nil {
		return v, err
	}
	h.mu.Lock()
	if h.m == nil {
		h.m = make(map[string]T)
	}
	h.m[host] = v
	h.mu.Unlock()
	return v, nil
}
