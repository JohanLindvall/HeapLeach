// Feeds resolves a syndication feed into the files it attaches: an RSS 2.0
// <enclosure>, or an Atom <link rel="enclosure">. That one element is how
// every podcast on the open web publishes its audio, and it is the whole of
// what this reads — the rest of a feed describes articles.
//
// Two things set it apart from the other extractors here. There is no host or
// path to know a feed by: it is served from wherever the publisher keeps it,
// so it is recognised by what the response is — its declared type or its
// root element — and a sitemap, an API dump or an OPML file is not one. And
// the document is XML rather than a page, so it is parsed with encoding/xml
// rather than the HTML parser, which decides how it fails:
//
//   - The parser runs non-strict with the HTML entity table, because feeds
//     are generated by a thousand different tools and a bare &nbsp; in one
//     episode's show notes is a hard error in strict XML. Losing a twenty-
//     year archive to one character in a description nobody reads would be
//     absurd, and none of that markup is anywhere near an enclosure.
//
// The enclosure's length attribute is an exact byte count written by the
// publisher's own tooling, not a figure a listing page rounded for display,
// so it is carried as an exact Size and an episode already on disk is skipped
// before a connection is opened. A publisher that splices adverts in at
// request time serves something longer than it advertised; the only
// consequence is that the file is fetched.
type Feeds struct {
	about
	client *httpx.Client
}

// feedAccept asks for a feed by name. Some hosts serve the subscribe page to
// a client that will take anything and the document itself to one that asks
// for it, so this is worth stating rather than leaving at */*.
const feedAccept = "application/rss+xml, application/atom+xml, application/xml;q=0.9, text/xml;q=0.9, */*;q=0.8"

// NewFeeds builds the syndication-feed extractor.
func NewFeeds(client *httpx.Client) *Feeds {
	return &Feeds{client: client, about: about{name: "feed", shape: feedShape,
		recognises: "RSS and Atom feeds, at any URL: a response served as a feed type, or whose document " +
			"element is `<rss>` or `<feed>`"}}
}

// Feed-shaped URLs: what the link scanner may probe. None of these is a
// promise — the document itself settles it — so they are deliberately the
// shapes publishers actually use rather than the narrowest set that could
// not be wrong.
var (
	// feedHostPrefixes are the subdomains publishers park feeds on.
	feedHostPrefixes = []string{"feeds.", "feed.", "rss."}
	// feedPathNames are the path segments a feed is published under.
	feedPathNames = []string{"feed", "feeds", "rss", "atom"}
	// feedFileExtensions name a feed document directly.
	feedFileExtensions = []string{".rss", ".atom", ".xml"}
)

// feedHost is a URL on a host named for its feeds, whatever its path: a
// publisher's feeds subdomain serves a show's feed at /<show-id>. It is a
// form the link scanner follows to another site (linkForms) and one the
// feed is asked for by name on, not part of the Shape: a feeds host may
// answer a browser with a subscribe page.
func feedHost(u *url.URL) bool {
	host := strings.ToLower(u.Hostname())
	for _, prefix := range feedHostPrefixes {
		if strings.HasPrefix(host, prefix) && len(host) > len(prefix) {
			return true
		}
	}
	return false
}

// feedShape is a URL that looks like a feed.
func feedShape(u *url.URL) bool {
	segs := util.PathSegments(u)
	for _, seg := range segs {
		if slices.Contains(feedPathNames, strings.ToLower(seg)) {
			return true
		}
	}
	if len(segs) > 0 {
		if ext := strings.ToLower(path.Ext(segs[len(segs)-1])); slices.Contains(feedFileExtensions, ext) {
			return true
		}
	}

	// WordPress and everything that copied it ask for a feed by parameter.
	_, wordpress := u.Query()["feed"]
	return wordpress
}

// feedFirst selects the feed reader's request policy before navigation can
// consume a feed-shaped source. A named media file or manifest keeps its
// normal HEAD or manifest acquisition, even below a /feed/ path.
func feedFirst(u *url.URL) bool {
	if u.Scheme != "http" && u.Scheme != "https" ||
		!feedShape(u) && !feedHost(u) || hlsManifestShape(u) || fileRoute(u) {
		return false
	}
	return probeWorthy(u) || slices.Contains(feedFileExtensions, strings.ToLower(path.Ext(u.Path)))
}

// initialPage acquires a possible feed with its reader's Accept first. The
// answer belongs only to this acquisition. A definite file needs no
// second request. Other non-feed answers still get ordinary navigation and
// recognition; their negative feed answer is kept too, so the later
// recognizer does not repeat that same question in an unchanged session.
func (f *Feeds) initialPage(ctx context.Context, u *url.URL, navigate func() *Page) *Page {
	answer := f.askFeed(ctx, u)
	p := answer.page
	file := answer.err == nil && followedFile(p) &&
		(!feedBinaryTypes[p.MediaType()] || !probeWorthy(u))
	if !answer.feed && !file && !probeTransient(ctx, answer.err) && ctx.Err() == nil {
		p = navigate()
	} else {
		p.Body = string(answer.body[:min(len(answer.body), config.FeedSniffBytes)])
		p.partial = answer.cut || len(answer.body) > len(p.Body)
		p.Err = answer.err
	}
	// Navigation can establish cookies needed by a feed. Its new session
	// must not inherit a negative answer obtained before those cookies.
	if answer.page.matchesSession(ctx, f.client) {
		memoAsked(ctx, p, feedAskKey+" "+u.String(), func() feedAnswer { return answer })
	}
	return p
}

// Recognise takes a response that is a syndication feed, by its declared
// type or its root element, whatever URL served it: a feed has no host or
// path of its own. A body past the probe's bound is still sniffed, since
// only its head decides and a long feed is still a feed.
//
// A feed-shaped URL or one on a feeds host (feedHost) can answer navigation
// with a refusal, a subscribe notice or an unread generic binary type.
// Those answers are asked again with the feed's own Accept: the browser's
// status and representation need not be the reader's. A successful feed
// response is kept for extraction, so negotiation cannot spend a single-use
// feed and then ask for it again. A transient failure keeps its error rather
// than turning a temporarily unavailable feed into an unsupported page.
func (f *Feeds) Recognise(ctx context.Context, p *Page) bool {
	if answer, asked := f.pageAnswer(ctx, p, p.URL); asked &&
		(answer.feed || probeTransient(ctx, answer.err)) {
		return true
	}
	if p.Status < 200 {
		return false
	}
	if p.Status < 300 && p.Body != "" && (p.Err == nil || httpx.IsTooLarge(p.Err)) &&
		feedish(p.Header.Get(httpx.HeaderContentType), []byte(p.Body[:min(len(p.Body), config.FeedSniffBytes)])) {
		return true
	}
	return p.Err == nil && f.negotiated(ctx, p)
}

// feedAskKey names a feed-specific request within one acquisition.
const feedAskKey = "feed-accept"

// feedAnswer is the response to a feed request, including its request
// identity after redirects and cookie updates. It lives only in the
// acquisition's memo, never the navigation page's shared cache.
type feedAnswer struct {
	page      *Page
	body      []byte
	kind      string
	feed, cut bool
	err       error
}

// negotiated reports whether a feed-shaped URL, or one on a feeds host,
// that the probe got no feed from — a navigation refusal, a binary type it
// did not read, an HTML page or a plain/untyped text notice — answers as a
// feed when asked for one by name. The submitted form survives redirects;
// negotiation starts from that URL because Accept can change the redirect
// destination too. A response that identifies a feed is read to the feed
// bound and kept for its reader. Exhausted transient errors also select this
// reader, which reports the actual error instead of claiming no support.
func (f *Feeds) negotiated(ctx context.Context, p *Page) bool {
	if f.client == nil || p.URL == nil || p.Final == nil ||
		(p.via != nil && !p.via.SameIdentity(f.client)) ||
		!feedShape(p.URL) && !feedHost(p.URL) && !feedShape(p.Final) && !feedHost(p.Final) {
		return false
	}
	kind := p.MediaType()
	unread := p.Body == "" && feedBinaryTypes[kind]
	// A successful media response is the file itself. A refusal's type
	// describes its error representation, not what the feed request gets.
	if p.Status < 300 && !unread && !mediaPageIsHTMLType(kind) && !probeSniffsType(kind) {
		return false
	}
	answer := memoAsked(ctx, p, feedAskKey+" "+p.URL.String(), func() feedAnswer {
		return f.askFeed(ctx, p.URL)
	})
	return answer.feed || probeTransient(ctx, answer.err)
}

// askFeed gives identification the same finite transient-failure patience
// as other optional platform questions. A negative content verdict is not
// retried, and each attempt releases its admission before waiting. A stated
// Retry-After uses the HTTP client's capped policy, never an earlier retry
// imposed by the shorter optional-probe backoff.
func (f *Feeds) askFeed(ctx context.Context, u *url.URL) (answer feedAnswer) {
	// Cancellation can arrive after the attempt releases its admission but
	// before the retry decision; it must still take precedence over the response.
	defer func() {
		if err := ctx.Err(); err != nil {
			answer.err = err
		}
	}()
	for attempt := 0; ; attempt++ {
		answer = f.askFeedOnce(ctx, u)
		if answer.err == nil || !probeTransient(ctx, answer.err) || attempt+1 >= config.PlatformProbeAttempts {
			return answer
		}
		wait := min(httpx.RetryDelay(attempt), config.PlatformProbeRetryWait)
		if status, ok := errors.AsType[*httpx.StatusError](answer.err); ok {
			if delay, stated := httpx.RetryAfter(status.Header); stated {
				if status.Code == http.StatusTooManyRequests {
					wait = delay
				} else {
					wait = max(wait, delay)
				}
			}
		}
		if err := util.SleepCtx(ctx, wait); err != nil {
			answer.err = err
			return answer
		}
	}
}

// askFeedOnce bounds the identification prefix by the probe timeout, then
// lets an identified feed finish under the caller's and HTTP client's
// ordinary reader timeouts. Keeping that response avoids a second use of a
// signed feed without imposing the short identification timeout on its body.
func (f *Feeds) askFeedOnce(ctx context.Context, u *url.URL) (answer feedAnswer) {
	answer.page = newProbePage(ctx, f.client, cloneURL(u))
	defer func() { answer.page.finishProbe(ctx) }()
	release, err := httpx.Admit(ctx)
	if err != nil {
		answer.err = err
		return answer
	}
	defer release()
	ask, cancel := context.WithCancelCause(httpx.WithoutAdmission(ctx))
	defer cancel(nil)
	timer := time.AfterFunc(platformProbeTimeout, func() { cancel(context.DeadlineExceeded) })
	defer timer.Stop()
	defer func() {
		if err := ctx.Err(); err != nil {
			answer.err = err
		} else if context.Cause(ask) == context.DeadlineExceeded {
			answer.err = fmt.Errorf("%s: identify feed: %w", u.Redacted(), context.DeadlineExceeded)
		}
	}()
	req, err := f.client.NewRequest(ask, http.MethodGet, u.String(), nil)
	if err != nil {
		answer.err = err
		return answer
	}
	req.Header.Set(httpx.HeaderAccept, feedAccept)
	started := time.Now()
	resp, err := f.client.DoOnce(req)
	if err != nil {
		answer.err = err
		return answer
	}
	defer resp.Body.Close()
	answer.page.Status, answer.page.Header, answer.page.Final = resp.StatusCode, resp.Header, resp.Request.URL
	answer.page.recordRedirects(resp, started)
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		answer.err = httpx.NewStatusError(resp)
		return answer
	}
	answer.kind = resp.Header.Get(httpx.HeaderContentType)
	answer.feed = feedish(answer.kind, nil)
	var head []byte
	if !answer.feed {
		kind := answer.page.MediaType()
		if !probeReadsType(kind) && !probeSniffsType(kind) && !feedBinaryTypes[kind] {
			// Specific media types are files, not feed candidates. Do not
			// read any of their bytes merely because the path looked like a feed.
			return answer
		}
		head, err = io.ReadAll(io.LimitReader(resp.Body, config.FeedSniffBytes))
		answer.feed = feedish(answer.kind, head)
		if err != nil {
			answer.err = fmt.Errorf("%s: read feed prefix: %w", resp.Request.URL.Redacted(), err)
			return answer
		}
	}
	if !answer.feed {
		return answer
	}
	timer.Stop()
	answer.body, answer.cut, answer.err = readFeedBody(resp, head)
	return answer
}

// askedFeed consumes only this acquisition's matching feed request. The
// navigation probe may no longer match after negotiation sets cookies, so
// the feed response's own identity decides reuse. New acquisitions have new
// memos; route, agent, client or later session changes require a fresh read.
func (f *Feeds) askedFeed(ctx context.Context, u *url.URL) (feedAnswer, bool) {
	return f.pageAnswer(ctx, attachedPage(ctx), u)
}

func (f *Feeds) pageAnswer(ctx context.Context, p *Page, u *url.URL) (feedAnswer, bool) {
	if p == nil || u == nil {
		return feedAnswer{}, false
	}
	key := feedAskKey + " " + u.String()
	p.memoMu.Lock()
	_, asked := p.memo[memoKey(ctx, key)]
	p.memoMu.Unlock()
	if !asked {
		return feedAnswer{}, false
	}
	answer := memoAsked(ctx, p, key, func() feedAnswer { return f.askFeed(ctx, u) })
	identity := answer.page
	return answer, identity != nil && identity.via.SameIdentity(f.client) &&
		identity.route == httpx.RouteID(ctx) && identity.agent == httpx.RequestAgent(ctx, f.client) &&
		identity.matchesSession(ctx, f.client)
}

// feedBinaryTypes are the generic types a feed is sometimes served as,
// which the probe does not read. A successful response with a specific
// media type is never taken for one: that is the file itself.
var feedBinaryTypes = map[string]bool{
	"application/octet-stream":   true,
	"binary/octet-stream":        true,
	"application/download":       true,
	"application/force-download": true,
}

// Extract reads the feed and lists its enclosures.
func (f *Feeds) Extract(ctx context.Context, u *url.URL, opts Options) (*Result, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	// The browser probe can recognise a feed, but its Accept may select
	// different enclosures even when it returned complete, valid XML. Read
	// the feed's own representation, including past any sniffed prefix.
	// Initial acquisition or later negotiation may already have acquired it.
	answer, asked := f.askedFeed(ctx, u)
	body, contentType, cut, err := answer.body, answer.kind, answer.cut, answer.err
	if !asked {
		body, contentType, cut, err = f.fetch(ctx, u)
	}
	if err != nil {
		return nil, fmt.Errorf("feed: fetch %s: %w", u.Redacted(), err)
	}

	if !feedish(contentType, body) {
		// The guess was wrong: this is a file like any other, and the
		// fallback extractor is what makes a file of a URL nobody claimed.
		// Handing it there is what would have happened had Match been able
		// to tell the difference without asking the server.
		return NewDirect(f.client).Extract(ctx, u, opts)
	}

	res, err := feedResult(body, u, opts.maxFiles())
	if err == nil && cut {
		res.Note = joinNotes(res.Note, partial(fmt.Sprintf("the feed runs past %d MiB; only the "+
			"episodes listed before that are queued", config.MaxFeedBytes>>20)))
	}
	return res, err
}

// fetch reads the document, asking for it as a feed, and reports the type
// it was served as: the declared content type is half of how a feed is
// recognised (see feedish). A feed is read past the ordinary response bound,
// to config.MaxFeedBytes, and one longer than that is cut there, reported
// in cut: its enclosures are whole entries, so the head still lists them.
func (f *Feeds) fetch(ctx context.Context, u *url.URL) (body []byte, contentType string, cut bool, err error) {
	req, err := f.client.NewRequest(ctx, http.MethodGet, u.String(), nil)
	if err != nil {
		return nil, "", false, err
	}
	req.Header.Set(httpx.HeaderAccept, feedAccept)
	resp, err := f.client.Do(req)
	if err != nil {
		return nil, "", false, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return nil, "", false, httpx.NewStatusError(resp)
	}
	body, cut, err = readFeedBody(resp, nil)
	return body, resp.Header.Get(httpx.HeaderContentType), cut, err
}

// readFeedBody reads the complete feed within its bound, retaining any
// prefix identification already consumed. A bounded prefix is never passed
// off as the complete feed; the same cut reporting serves both acquisition
// paths.
func readFeedBody(resp *http.Response, prefix []byte) (body []byte, cut bool, err error) {
	body, err = io.ReadAll(io.LimitReader(io.MultiReader(bytes.NewReader(prefix), resp.Body), config.MaxFeedBytes+1))
	if err != nil {
		return nil, false, fmt.Errorf("%s: read body: %w", resp.Request.URL.Redacted(), err)
	}
	if len(body) > config.MaxFeedBytes {
		body, cut = body[:config.MaxFeedBytes], true
	}
	return body, cut, nil
}

// feedContentTypes are the types that settle the question on their own.
var feedContentTypes = []string{
	"application/rss+xml",
	"application/atom+xml",
	"application/x-rss+xml",
	"application/x-atom+xml",
}

// feedish reports whether what came back is a syndication feed.
//
// Both halves are needed, and each covers the other's blind spot. A server
// that names one of the feed types is believed outright, because a great many
// feeds are otherwise served as text/xml, as text/plain, or as whatever the
// cache in front of them invented — and a host that declares RSS and then
// serves rubbish should fail loudly rather than have its rubbish quietly
// downloaded. The other direction is why the body is looked at at all:
// sitemaps, API dumps and OPML files are every bit as much application/xml as
// a feed is.
//
// The body half asks the parser for the first element rather than searching
// the text for "<?xml" and "<rss". Feeds omit the prolog often enough, and
// the substring test cannot tell a document from a page that merely mentions
// one, whereas the root element is exactly the question being asked.
func feedish(contentType string, body []byte) bool {
	if slices.Contains(feedContentTypes, feedMediaType(contentType)) {
		return true
	}
	switch feedRoot(body) {
	case "rss", "feed":
		return true
	}
	return false
}

// feedRoot returns the lower-cased local name of the document's first
// element, or "" when there is none to read. The namespace is ignored: Atom
// declares one and RSS does not, and neither fact is worth acting on.
func feedRoot(body []byte) string {
	dec := feedDecoder(body[:min(len(body), config.FeedSniffBytes)])
	for {
		tok, err := dec.Token()
		if err != nil {
			return ""
		}
		if start, ok := tok.(xml.StartElement); ok {
			return strings.ToLower(start.Name.Local)
		}
	}
}

// feedMediaType strips the parameters from a Content-Type or a type attribute,
// which arrive with charsets and codecs appended often enough to matter.
func feedMediaType(value string) string {
	main, _, _ := strings.Cut(value, ";")
	return strings.ToLower(strings.TrimSpace(main))
}

// feedResult parses a feed document into a job.
func feedResult(body []byte, u *url.URL, limit int) (*Result, error) {
	var doc feedDocument
	err := feedDecoder(body).Decode(&doc)

	files := feedFiles(&doc, u, limit)
	// A document cut short in transit still lists everything that arrived:
	// the decoder fills the struct as it goes, and an enclosure is a single
	// self-closed element, so what was recovered is whole entries rather
	// than fragments. Turning one dropped connection into no download at all
	// would be the worse answer — but a document that yielded nothing is
	// reported as the parse failure it is.
	if err != nil && len(files) == 0 {
		return nil, fmt.Errorf("feed: parse %s: %w", u.Redacted(), err)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("feed: %s attaches no files — an article feed links to pages "+
			"rather than enclosing media, so there is nothing here to download", u.Redacted())
	}

	return &Result{Title: cmp.Or(doc.title(), strings.Trim(u.Path, "/")), Files: files}, nil
}

// feedFiles turns the parsed document into the download list.
func feedFiles(doc *feedDocument, u *url.URL, limit int) []File {
	var kept []feedEnclosure
	seen := make(map[string]bool)
	for _, enc := range doc.enclosures() {
		link := resolveRef(u, enc.url)
		// A feed that attaches the same file to two entries — a re-run, a
		// corrected post — would otherwise queue the same bytes twice.
		if link == "" || seen[link] {
			continue
		}
		seen[link] = true
		enc.url = link
		kept = append(kept, enc)

		// A show twenty years deep is a nine-hundred-file job from one
		// paste, so the list is capped. What the cap drops is the far end of
		// the back catalogue rather than last week's episodes, because a
		// feed is newest-first and the cut is made before reversing:
		// dropping the newest instead would mean a second run months later
		// fetched the same oldest N again and never reached anything new.
		if len(kept) == limit {
			break
		}
	}
	// Reversed, because a feed is published newest-first and an archive is
	// wanted oldest-first: the queue then runs in the order the show was
	// made, and an interrupted run resumes where the story left off.
	slices.Reverse(kept)

	used := make(map[string]int, len(kept))
	files := make([]File, 0, len(kept))
	for _, enc := range kept {
		files = append(files, File{
			Name: feedFileName(enc.title, enc.url, enc.media, used),
			URL:  enc.url,
			// The enclosure's length is exact, which is what makes it worth
			// carrying: an episode already on disk at that length is skipped
			// without connecting. A feed that omits it, writes 0 or writes no
			// number at all is saying the same thing three ways — whole
			// hosting platforms write length="0" on every episode — so an
			// unknown length is the ordinary case rather than the broken one.
			Size: parsedSize(enc.length),
			// No headers: an enclosure is published to be fetched by any
			// podcast client in the world, and the analytics redirectors in
			// front of one care about nothing but the user agent, which the
			// shared client already sends.
		})
	}
	return files
}

// feedSlashes folds the separators out of an episode title.
//
// SafeName has to treat a slash as a path separator and keeps only what
// follows the last one, so "S2E4: Vinyl / Digital" would land on disk as
// "Digital". Here the difference is still known: this is prose, not a path.
var feedSlashes = strings.NewReplacer("/", "-", `\`, "-")

// feedFileName names the saved file after the episode.
//
// The title is what a listener recognises, so that is the name; the extension
// has to come from elsewhere, since a title carries none. Where from is the
// interesting part. These URLs are routinely wrapped by analytics
// redirectors, which prepend their own path — a tracker's hostname, then
// "redirect.mp3", then the publisher's real URL — so it is the *last* path
// segment that is the publisher's own filename and the first that is the
// tracker's. Nothing is resolved to find that out, and nothing needs to be: a
// redirector wraps rather than replaces, so the real name is already there,
// at the end.
func feedFileName(title, link, mediaType string, used map[string]int) string {
	base := util.NameFromURL(link)
	name := strings.TrimSpace(feedSlashes.Replace(strings.TrimSpace(title)))
	if name == "" {
		name = base
	}
	if name == "" {
		name = "episode"
	}
	if ext := feedExtension(base, mediaType); ext != "" && !strings.EqualFold(path.Ext(name), ext) {
		name += ext
	}
	return feedUnique(used, name)
}

// feedTypeExt maps the media types feeds publish to a file extension.
//
// mime.ExtensionsByType is not used for this. It answers from the system's
// mime.types, so the name a download lands under would depend on which
// distribution the binary happens to be running on — and for audio/mpeg, the
// answer it offers first is ".mp2".
var feedTypeExt = map[string]string{
	"audio/mpeg":           ".mp3",
	"audio/mp3":            ".mp3",
	"audio/mp4":            ".m4a",
	"audio/x-m4a":          ".m4a",
	"audio/aac":            ".aac",
	"audio/aacp":           ".aac",
	"audio/ogg":            ".ogg",
	"audio/vorbis":         ".ogg",
	"audio/opus":           ".opus",
	"audio/flac":           ".flac",
	"audio/x-flac":         ".flac",
	"audio/wav":            ".wav",
	"audio/x-wav":          ".wav",
	"video/mp4":            ".mp4",
	"video/x-m4v":          ".m4v",
	"video/quicktime":      ".mov",
	"video/webm":           ".webm",
	"video/x-matroska":     ".mkv",
	"image/jpeg":           ".jpg",
	"image/png":            ".png",
	"application/pdf":      ".pdf",
	"application/epub+zip": ".epub",
	"application/zip":      ".zip",
}

// feedMediaExtensions are the suffixes trusted when the URL itself carries
// one, built from the types above so the two cannot drift apart.
var feedMediaExtensions = func() map[string]bool {
	out := make(map[string]bool, len(feedTypeExt))
	for _, ext := range feedTypeExt {
		out[ext] = true
	}
	// Extensions no type in the table spells, but a publisher writes.
	for _, ext := range []string{".mp2", ".oga", ".m4b", ".aiff", ".wma", ".avi", ".mpg", ".mpeg"} {
		out[ext] = true
	}
	return out
}()

// feedExtension decides what to call the file.
//
// The URL's own extension wins over the declared type, because the type
// attribute is the field publishers are careless with: audio/mpeg is what a
// great many tools emit whatever the file actually is, and an .m4a saved as
// .mp3 confuses every player that trusts the name. The type is consulted
// second, for the wrapped URLs whose final segment is a bare id with no
// suffix at all — that is the case the redirectors create. A suffix that is
// neither a media extension nor a plausible one at all (".php", a trailing
// number) is dropped rather than carried onto the name.
func feedExtension(base, mediaType string) string {
	ext := strings.ToLower(path.Ext(base))
	if feedMediaExtensions[ext] {
		return ext
	}
	if fromType := feedTypeExt[feedMediaType(mediaType)]; fromType != "" {
		return fromType
	}
	if feedPlausibleExt(ext) {
		return ext
	}
	return ""
}

// feedPlausibleExt reports whether a suffix reads as a file extension: short,
// and letters only. It keeps an unusual but real format (".aif", ".spx")
// while rejecting the dotted ids and version numbers URLs are full of.
func feedPlausibleExt(ext string) bool {
	if len(ext) < 3 || len(ext) > 6 || !strings.HasPrefix(ext, ".") {
		return false
	}
	for _, r := range ext[1:] {
		if r < 'a' || r > 'z' {
			return false
		}
	}
	return true
}

// feedUnique keeps two episodes with the same title from writing to one file.
// "Trailer" and "Bonus" recur down a long feed, and the download directory
// has room for one of each.
//
// Only the repeats are numbered, so every other episode keeps exactly the
// name it is published under, and the numbering is assigned after the list
// has been reversed — oldest first — so the first "Bonus" ever published is
// the plain one and the later ones count up from it, which is both the
// chronological reading and the one that stays put as the feed grows.
func feedUnique(used map[string]int, name string) string {
	key := strings.ToLower(name)
	used[key]++
	if n := used[key]; n > 1 {
		ext := path.Ext(name)
		return fmt.Sprintf("%s (%d)%s", strings.TrimSuffix(name, ext), n, ext)
	}
	return name
}

// feedDecoder builds the parser, and is used for both sniffing and parsing so
// the two can never disagree about what the document is.
//
// Strict parsing is off deliberately. Feeds are generated by everything from
// a hand-written template upwards, and a bare &nbsp;, an unescaped ampersand
// in a title or an unclosed <b> in a description are all hard errors to a
// strict parser — none of them anywhere near an enclosure, and any one of
// them enough to lose the whole archive.
func feedDecoder(body []byte) *xml.Decoder {
	dec := xml.NewDecoder(bytes.NewReader(body))
	dec.Strict = false
	dec.Entity = xml.HTMLEntity
	dec.CharsetReader = feedCharset
	return dec
}

// feedCharset accepts the single-byte encodings older feeds still declare.
//
// encoding/xml refuses outright to parse a document whose declared encoding
// is not UTF-8 unless it is handed a reader for it, so without this an
// ISO-8859-1 feed fails completely rather than merely mis-spelling a title.
// Each byte is read as the code point of the same value, which is exactly
// right for ISO-8859-1 and near enough for its neighbours: everything acted
// on here — URLs, lengths, media types — is ASCII in all of them, and the
// only casualty is the odd piece of punctuation in a filename.
//
// input is the rest of a feed already read within the feed's own limit
// (Feeds.fetch reads up to config.MaxFeedBytes, the probe less), so it is
// bounded by that limit rather than the response limit: a long feed in a
// legacy charset is read as far as a UTF-8 one. The bound is on bytes in:
// the decoded text is at most twice that, since each byte above 0x7f
// becomes a two-byte rune.
func feedCharset(_ string, input io.Reader) (io.Reader, error) {
	raw, err := io.ReadAll(io.LimitReader(input, config.MaxFeedBytes))
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.Grow(len(raw))
	for _, c := range raw {
		b.WriteRune(rune(c))
	}
	return strings.NewReader(b.String()), nil
}

// feedDocument covers both dialects in one struct.
//
// The element names carry no namespace on purpose: encoding/xml then matches
// on the local name alone, which is what lets one document type read an Atom
// feed (namespaced) and an RSS one (not) without asking which arrived. RSS
// 1.0 is not covered — it hangs its items off <rdf:RDF> and attaches them
// with an element from a module that barely outlived the format.
type feedDocument struct {
	// Title is Atom's feed title. RSS keeps its own inside <channel>, so
	// this stays empty there.
	Title   string       `xml:"title"`
	Channel *feedChannel `xml:"channel"`
	Entries []feedEntry  `xml:"entry"`
}

// feedChannel is the RSS 2.0 <channel>.
type feedChannel struct {
	Title string     `xml:"title"`
	Items []feedItem `xml:"item"`
}

// feedItem is one RSS entry. An item may carry more than one enclosure —
// the specification says otherwise, but feeds do it — and each is a file.
type feedItem struct {
	Title      string        `xml:"title"`
	Enclosures []feedAttachA `xml:"enclosure"`
}

// feedAttachA is an RSS <enclosure>. Nothing else in an item is read: the
// media: and itunes: elements alongside it describe artwork and previews,
// and <media:content> in particular is a near-identical decoy carrying a url,
// a type and a length of its own. It is a different element, so it is not
// matched, and that is the whole of why this only ever names one.
type feedAttachA struct {
	URL    string `xml:"url,attr"`
	Type   string `xml:"type,attr"`
	Length string `xml:"length,attr"`
}

// feedEntry is one Atom entry.
type feedEntry struct {
	Title string     `xml:"title"`
	Links []feedLink `xml:"link"`
}

// feedLink is an Atom <link>, of which an entry has several.
type feedLink struct {
	Rel    string `xml:"rel,attr"`
	Href   string `xml:"href,attr"`
	Type   string `xml:"type,attr"`
	Length string `xml:"length,attr"`
}

// feedEnclosure is one attached file, normalised out of either dialect.
type feedEnclosure struct {
	title  string
	url    string
	media  string
	length string
}

// title names the job after the publication.
func (d *feedDocument) title() string {
	if d.Channel != nil {
		return strings.TrimSpace(d.Channel.Title)
	}
	return strings.TrimSpace(d.Title)
}

// enclosures flattens both dialects into one list, in the document's own
// order — which is newest first, and reversed later.
func (d *feedDocument) enclosures() []feedEnclosure {
	var out []feedEnclosure
	if d.Channel != nil {
		for _, item := range d.Channel.Items {
			for _, enc := range item.Enclosures {
				out = append(out, feedEnclosure{
					title: item.Title, url: enc.URL, media: enc.Type, length: enc.Length,
				})
			}
		}
	}
	for _, entry := range d.Entries {
		for _, link := range entry.Links {
			if !feedIsEnclosure(link.Rel) {
				continue
			}
			out = append(out, feedEnclosure{
				title: entry.Title, url: link.Href, media: link.Type, length: link.Length,
			})
		}
	}
	return out
}

// feedIsEnclosure reports whether an Atom link is an attachment.
//
// The relation has to be tested rather than the link's position or its type:
// an entry's other links are the article itself, its comments and its author,
// and a link with no rel at all means "alternate" — the web page — which is
// the one mistake here that would download a page of HTML per episode.
// Atom also permits the registered relation to be written as its full IANA
// URI, which a handful of generators do.
func feedIsEnclosure(rel string) bool {
	rel = strings.ToLower(strings.TrimSpace(rel))
	return rel == "enclosure" || strings.HasSuffix(rel, "/relation/enclosure")
}
